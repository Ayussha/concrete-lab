/*
 * build.js — makes index.html a single self-contained file
 * --------------------------------------------------------
 * dev.html loads the stylesheet and scripts as separate files, which is
 * convenient for editing but breaks if the page is opened on its own,
 * without the css/ and js/ folders beside it. This script inlines all of
 * them into index.html so that one file is the whole app: double-click it,
 * copy it to a USB stick, email it — it still works.
 *
 * Edit the files in css/ and js/, then run:   node build.js
 * Never edit index.html by hand; it is overwritten on every build.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');

let html = read('dev.html');

/* A literal "</script" or "</style" inside inlined code would end the
   tag early. Escaping the slash is harmless in JS strings and CSS. */
const safeScript = s => s.replace(/<\/script/gi, '<\\/script');
const safeStyle = s => s.replace(/<\/style/gi, '<\\/style');

let inlined = 0;

/* stylesheet */
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => {
  inlined++;
  return '<style>\n/* ' + href + ' */\n' + safeStyle(read(href)) + '\n</style>';
});

/* icon, as a data URI so it needs no file beside the page */
html = html.replace(/<link rel="icon" href="([^"]+\.svg)" type="image\/svg\+xml">/, (m, href) => {
  inlined++;
  const svg = read(href).replace(/\s+/g, ' ').trim();
  return '<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,' +
    encodeURIComponent(svg) + '">';
});

/* The manifest only means something when the app is served over http(s)
   (installing it as an app from GitHub Pages). Opened as a local file,
   Chrome refuses to load it and logs an error, so add it only when served. */
html = html.replace(/<link rel="manifest" href="([^"]+)">/, (m, href) =>
  '<script>if (location.protocol !== "file:") { var l = document.createElement("link"); ' +
  'l.rel = "manifest"; l.href = "' + href + '"; document.head.appendChild(l); }</script>');

/* scripts */
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => {
  inlined++;
  return '<script>\n/* ' + src + ' */\n' + safeScript(read(src)) + '\n</script>';
});

const banner = '<!-- Built from dev.html by build.js. Do not edit this file: ' +
  'edit css/, js/ or dev.html and run "node build.js". -->\n';
html = html.replace(/^<!DOCTYPE html>\n/i, '<!DOCTYPE html>\n' + banner);

/* Fail loudly if anything still points at a local file. */
const leftovers = html.match(/<(script|link)[^>]+(src|href)="(?!data:|https?:)[^"]+"[^>]*>/g) || [];
const allowed = leftovers.filter(t => !/rel="manifest"/.test(t));
if (allowed.length) {
  console.error('build.js: these still reference separate files:\n  ' + allowed.join('\n  '));
  process.exit(1);
}

fs.writeFileSync(path.join(ROOT, 'index.html'), html);
console.log('index.html built: ' + inlined + ' files inlined, ' +
  Math.round(html.length / 1024) + ' KB, no external files needed.');
